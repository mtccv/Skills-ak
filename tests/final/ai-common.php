final class AishQaProvider implements Provider {
	public string $scenario = 'valid'; public string $lastProvider = ''; public array $calls = array(); public ?Closure $before = null;
	public function generate( array $profile, array $messages, string $requestId ): array {
		$this->lastProvider = $profile['provider']; $this->calls[] = compact( 'profile', 'messages', 'requestId' );
		if ( $this->before ) { ( $this->before )(); }
		if ( 'rate' === $this->scenario ) { throw new ProviderException( 'ai_rate_limited', true, 120 ); }
		if ( 'timeout' === $this->scenario ) { throw new ProviderException( 'ai_request_timeout', false, 0, true ); }
		if ( 'error' === $this->scenario ) { throw new RuntimeException( 'synthetic-private-error-must-not-persist' ); }
		$mode = preg_match( '/Mode=([A-Za-z_]+);/', $messages[0]['content'], $m ) ? $m[1] : 'connection';
		$content = 'connection' === $mode ? '{"ok":true}' : json_encode( self::output( $mode ), JSON_THROW_ON_ERROR | JSON_UNESCAPED_UNICODE );
		if ( 'invalid' === $this->scenario ) { $content = '{'; }
		if ( 'duplicate' === $this->scenario ) { $content = 'connection' === $mode ? '{"ok":false,"ok":true}' : str_replace( '"risk":', '"risk":{},"risk":', $content ); }
		return array( 'content' => $content, 'input_tokens' => 'unknown' === $this->scenario ? null : 1000, 'output_tokens' => 'unknown' === $this->scenario ? null : 250, 'elapsed_ms' => 25 );
	}
	public static function output( string $mode ): array {
		$locales = array();
		foreach ( Prompt::locales( $mode ) as $locale ) {
			$zh = 'zh_CN' === $locale;
			$full = array( 'title' => $zh ? '测试代码审查助手' : 'QA code review helper', 'summary' => $zh ? '用于人工代码审查的测试草稿。' : 'A synthetic draft for human code review.', 'description' => $zh ? '本内容为受控测试响应，须人工核对。' : 'This controlled test response requires human review.', 'key_features' => array( $zh ? '整理审查问题' : 'Organize review concerns' ), 'tasks' => array(), 'use_cases' => array( $zh ? '审查前整理变更' : 'Prepare changes for review' ), 'installation' => array( 'status' => 'needs_verification', 'steps' => array(), 'note' => $zh ? '来源未明确安装步骤，待核实。' : 'Source installation steps are unknown and require verification.' ), 'requirements' => array(), 'limitations' => array( $zh ? '未经真实模型生成。' : 'Not generated by a real model.' ), 'safety_notes' => array( $zh ? '不能替代人工审核。' : 'Human review is required.' ) );
			$locales[ $locale ] = in_array( $mode, array( 'summary', 'use_cases' ), true ) ? array( $mode => $full[ $mode ] ) : $full;
		}
		return array( 'locales' => $locales, 'suggestions' => array( 'categories' => array(), 'tags' => array(), 'platforms' => array(), 'scenarios' => array() ), 'risk' => array( 'level' => 'unknown', 'findings' => array(), 'limitations' => array( 'Synthetic test output does not establish safety.' ) ) );
	}
}
